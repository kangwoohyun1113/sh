    a, b, c = st.columns(3)
    with a:
        age = st.number_input("나이", min_value=10, max_value=100, value=17)
        height = st.number_input("키 (cm)", min_value=100.0, max_value=230.0, value=170.0, step=0.5)
    with b:
        weight = st.number_input("체중 (kg)", min_value=20.0, max_value=300.0, value=65.0, step=0.5)
        muscle = st.number_input("골격근량 (kg)", min_value=1.0, max_value=150.0, value=28.0, step=0.1)
    with c:
        fat_mass = st.number_input("체지방량 (kg)", min_value=0.0, max_value=150.0, value=12.0, step=0.1)
        body_fat = st.number_input("체지방률 (%)", min_value=1.0, max_value=70.0, value=18.0, step=0.1)

    st.header("2. 운동 경험과 목표")
