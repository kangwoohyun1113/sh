if submitted:
    errors = []
    if muscle + fat_mass > weight * 1.15:
        errors.append("골격근량과 체지방량의 합이 체중에 비해 큽니다. 입력한 수치를 다시 확인해 주세요.")
    if fat_mass > weight:
        errors.append("체지방량은 체중보다 클 수 없습니다. 입력값을 확인해 주세요.")
    if body_fat > 70:
        errors.append("체지방률 입력값을 확인해 주세요.")

    if errors:
        for msg in errors:
            st.error(msg)
    else:
        bmi = weight / ((height / 100) ** 2)
        st.header("3. 입력 정보 요약")
        c1, c2, c3, c4 = st.columns(4)
        c1.metric("BMI 참고값", f"{bmi:.1f}")
        c2.metric("골격근량", f"{muscle:.1f} kg")
        c3.metric("체지방량", f"{fat_mass:.1f} kg")
        c4.metric("체지방률", f"{body_fat:.1f}%")

        st.info(
            "인바디 결과만으로 근력, 체력, 건강 상태를 정확히 진단할 수는 없습니다. "
            "체지방률과 골격근량은 연령, 성별, 측정 조건 등에 따라 해석이 달라질 수 있습니다."
        )
